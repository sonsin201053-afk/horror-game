import streamlit as st

st.title("ยินดีต้อนรับสู่เกมสยองขวัญ 👻")

# 1. กล่องรับชื่อ (ให้คนเล่นกรอก)
# 'username' คือตัวแปรที่จะเก็บชื่อที่ออมพิมพ์เข้าไป
username = st.text_input("กรอกชื่อของคุณก่อนจะเข้าไปเจอความสยอง:")

# 2. ปุ่มกด (จะทำงานก็ต่อเมื่อออมกรอกชื่อแล้ว)
if st.button("เริ่มเกม!"):
    if username:  # ตรวจสอบว่าถ้าออมกรอกชื่อมาแล้ว ถึงจะให้ทำข้างล่างนี้
        st.write(f"สวัสดีคุณ {username} เตรียมตัวให้พร้อมนะครับ... ความสยองกำลังรอคุณอยู่!")
        st.balloons() # เอฟเฟกต์ลูกโป่ง
    else:
        # ถ้ายังไม่กรอกชื่อแล้วกดปุ่ม
        st.error("เฮ้ย! ยังไม่ได้กรอกชื่อเลย จะกลัวก่อนหรือไง!")